function buildArticles({ read, write, esc, SITE, urls }) {
  // 처리방침 페이지 머리(통계·글꼴·스타일)를 그대로 씀 (study.js 와 같은 방식)
  const pv = read('privacy.html');
  const headTpl = pv.slice(0, pv.indexOf('<main class="container policy">'));
  const head = (title, desc, url) =>
    headTpl
      .replace(/\s*<meta name="description"[^>]*>/, '')
      .replace(/\s*<link rel="canonical"[^>]*>/, '')
      .replace(/<title>[^<]*<\/title>/, `<title>${esc(title)}</title>\n  <meta name="description" content="${esc(desc)}">\n  <link rel="canonical" href="${url}">`)
      .replace(/href="icons\//g, 'href="/icons/')
      .replace(/src="icons\//g, 'src="/icons/')
      .replace('href="style.css"', 'href="/style.css"');
  const foot = `<p class="meta" style="text-align:center"><a href="/">← 맞혀봐 홈</a> · <a href="/guide/">읽을거리</a> · <a href="/study/">공부하기</a> · <a href="/about.html">소개</a> · <a href="/terms.html">이용약관</a> · <a href="/privacy.html">개인정보 처리방침</a></p>
  </main>
  <script src="/holiday.js"></script>
</body>
</html>
`;
  for (const a of ARTICLES) {
    const others = ARTICLES.filter((x) => x.id !== a.id).slice(0, 5);
    const url = `${SITE}/guide/${a.id}/`;
    write(
      `guide/${a.id}/index.html`,
      `${head(`${a.title} - 맞혀봐 읽을거리`, a.desc, url)}<main class="container policy">
    <h1>${esc(a.title)}</h1>
    <p class="meta">맞혀봐 읽을거리</p>
    ${a.sections.map(([h, ps]) => `<section>${h ? `<h2>${esc(h)}</h2>` : ''}${ps.map((p) => `<p>${esc(p)}</p>`).join('')}</section>`).join('\n    ')}
    <section><h2>직접 해 보기</h2><ul>${a.links.map(([u, t]) => `<li><a href="${u}">${esc(t)}</a></li>`).join('')}</ul></section>
    <section><h2>다른 글</h2><ul>${others.map((x) => `<li><a href="/guide/${x.id}/">${esc(x.title)}</a></li>`).join('')}</ul></section>
    ${foot}`
    );
    urls.push(`/guide/${a.id}/`);
  }
  write(
    'guide/index.html',
    `${head('읽을거리 - 공부법·맞춤법·상식·확률 이야기 | 맞혀봐', '퀴즈와 게임에 얽힌 지식을 직접 정리한 글 모음이에요. 공부법, 맞춤법, 세계 수도, 확률, 반응속도, 사주와 타로 이야기.', `${SITE}/guide/`)}<main class="container policy">
    <h1>읽을거리</h1>
    <p class="meta">퀴즈와 게임에 얽힌 지식을 맞혀봐가 직접 정리한 글이에요</p>
    ${ARTICLES.map((a) => `<section><h2><a href="/guide/${a.id}/">${esc(a.title)}</a></h2><p>${esc(a.desc)}</p></section>`).join('\n    ')}
    ${foot}`
  );
  urls.push('/guide/');
}

module.exports = { buildArticles, ARTICLES };
