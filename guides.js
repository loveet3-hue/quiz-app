// 퀴즈·게임 화면 아래에 붙는 소개 글 (어떤 퀴즈인지, 푸는 방법, 문제 예시, 게임 규칙·팁).
// 화면(app.js·games.js)과 검색용 정적 페이지(tools/build_pages.js)가 같이 씀.

const guideEsc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

const FORMAT_NAMES = { chosung: '초성 퀴즈', image: '이미지 퀴즈', text: '문제 퀴즈', sound: '소리 퀴즈' };

// 문제 예시를 고를 때 매번 같은 문제가 나오게 (검색 로봇이 볼 때마다 글이 바뀌지 않도록)
function guidePick(list, n) {
  if (list.length <= n) return list.slice();
  const step = list.length / n;
  return Array.from({ length: n }, (_, i) => list[Math.floor(i * step + step / 2)]);
}

function guideQuestionText(q) {
  if (q.big && q.text) return `${q.big} — ${q.text}`;
  if (q.text && q.ask && q.ask !== '정답은?') return `${q.text} ${q.ask}`;
  return q.text || q.big || '';
}

// 이 퀴즈에 나오는 문제·정답 전체 (접어 둠). 글 문제는 '문제 → 정답', 사진·소리 문제는 정답 이름만
// 퀴즈 페이지마다 내용이 다르게 보이도록 넣음 (2026-11 애드센스 '가치가 별로 없는 콘텐츠' 거절 대응)
function allAnswersHtml(qs, E) {
  if (!qs || qs.length < 8) return '';
  const rows = qs.map((q) => {
    const t = !q.image && !q.melody ? guideQuestionText(q) : '';
    const alias = q.alias && q.alias.length ? ` <span class="about-alias">(${q.alias.map(E).join(', ')})</span>` : '';
    return t ? `<li><span>${E(t)}</span> → <b>${E(q.answer)}</b>${alias}</li>` : `<li><b>${E(q.answer)}</b>${alias}</li>`;
  });
  return `<h3>이 퀴즈에 나오는 문제와 정답 ${qs.length}개</h3><details class="about-all"><summary>전체 정답 보기 (스포일러 주의)</summary><ol class="about-all-list">${rows.join('')}</ol></details>`;
}

function quizAboutHtml(quiz, all) {
  const E = guideEsc;
  const qs = quiz.generate ? [] : quiz.questions.filter((q) => !q.appHidden);
  const total = quiz.generate ? '풀 때마다 새로 만들어지는' : `모두 ${qs.length}개의`;
  const per = quiz.perPlay || 10;
  const fmt = FORMAT_NAMES[quiz.format] || '퀴즈';
  const how = [
    '문제를 보고 떠오르는 정답을 입력칸에 쓴 뒤 <b>확인</b>(또는 엔터)을 누르세요.',
    quiz.format === 'chosung' ? '화면에 크게 보이는 초성과 설명을 함께 보면 훨씬 쉬워요.' : '막히면 <b>힌트 보기</b>를 누르면 초성이나 첫 글자를 알려 줘요.',
    quiz.exact ? '이 퀴즈는 맞춤법을 묻는 문제라 글자 하나까지 정확히 써야 정답이에요.' : '띄어쓰기나 가벼운 오타는 정답으로 인정하고, 널리 쓰이는 다른 이름도 함께 인정해요.',
    '정말 모르겠으면 <b>모르겠어요</b>를 눌러 정답을 확인하고 다음 문제로 넘어가요.',
    `한 판은 ${per}문제이고, 끝나면 맞힌 개수와 걸린 시간이 기록돼요. 이미 본 문제는 다음 판에 뒤로 밀려요.`,
  ];
  if (quiz.guide) how.splice(1, 0, `답 쓰는 법: ${E(quiz.guide)}`);

  let samples = '';
  if (qs.length) {
    const pick = guidePick(qs, 5);
    const textual = pick.filter((q) => !q.image && !q.melody && guideQuestionText(q));
    if (textual.length >= 3) {
      samples = `<h3>이런 문제가 나와요</h3><ol class="about-samples">${textual
        .map((q) => `<li><span>${E(guideQuestionText(q))}</span><details><summary>정답 보기</summary>${E(q.answer)}</details></li>`)
        .join('')}</ol>`;
    } else {
      const names = guidePick(qs, 10).map((q) => q.answer);
      samples = `<h3>이런 정답이 나와요</h3><details class="about-names"><summary>정답 예시 보기 (스포일러 주의)</summary><p>${names.map(E).join(' · ')} 등 ${qs.length}개</p></details>`;
    }
  }

  const related = (all || [])
    .filter((x) => x.id !== quiz.id && (x.category === quiz.category || x.format === quiz.format))
    .slice(0, 6);

  return `<section class="about">
    <h2>${E(quiz.title)} 소개</h2>
    <p>${E(quiz.desc)}. ${E(quiz.category)} 분야의 ${fmt}로, ${total} 문제 가운데 한 판에 ${per}문제가 무작위로 나와요.
      보기 중에 고르는 객관식이 아니라 정답을 직접 떠올려 써야 해서, 알고 있다고 생각했던 것도 의외로 헷갈릴 수 있어요.</p>
    <h3>푸는 방법</h3>
    <ul>${how.map((h) => `<li>${h}</li>`).join('')}</ul>
    ${samples}
    ${allAnswersHtml(qs, E)}
    ${quiz.credit ? `<p class="about-note">${E(quiz.credit)}</p>` : ''}
    ${typeof STUDY_PAGES !== 'undefined' && STUDY_PAGES[quiz.id] ? `<h3>미리 공부하기</h3><p><a href="/study/${quiz.id}/">${E(STUDY_PAGES[quiz.id])}</a>에서 이 퀴즈에 나오는 내용을 표로 한눈에 정리해 두었어요.</p>` : ''}
    ${related.length ? `<h3>함께 풀어 볼 퀴즈</h3><ul class="about-links">${related.map((x) => `<li><a href="/q/${x.id}/">${E(x.title)}</a> — ${E(x.desc)}</li>`).join('')}</ul>` : ''}
  </section>`;
}

